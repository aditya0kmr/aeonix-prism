"""
Reporter Agent — Synthesis & Briefing Formatter
Compiles structured intelligence briefs, executive summaries, forensic manifests,
and compact JSON layout intent for the Fire TV Living Surface.
"""

import time
from typing import Dict, Any, List
from agents.base_agent import BaseAgent


class ReporterAgent(BaseAgent):
    def __init__(self):
        super().__init__(
            name="Reporter",
            role="Intelligence Synthesizer & Living Surface Formatter",
            allowed_tools=["format_briefing", "render_card_payload", "export_markdown"],
            forbidden_tools=["alter_raw_data", "suppress_findings"],
            base_risk_tier="R0",
        )

    def generate_briefing(self, title: str, sections: List[Dict[str, str]], author: str = "ÆONIX Core") -> Dict[str, Any]:
        md_lines = [
            f"# {title}",
            f"**Generated by:** {author} | **Timestamp:** {time.strftime('%Y-%m-%d %H:%M:%S')}",
            "---",
        ]
        cards = []
        for sec in sections:
            header = sec.get("title", "Section")
            content = sec.get("content", "")
            md_lines.append(f"\n### {header}\n{content}")
            cards.append({
                "title": header,
                "content": content,
                "type": "briefing",
            })

        return {
            "title": title,
            "markdown": "\n".join(md_lines),
            "layout_intent": {
                "screen": "living_surface",
                "theme": "obsidian_cyan",
                "headline": title,
                "cards": cards,
            },
        }

    def execute(self, mission_context: Dict[str, Any]) -> Dict[str, Any]:
        title = mission_context.get("title", "ÆONIX Intelligence Brief")
        sections = mission_context.get("sections", [{"title": "Overview", "content": "All systems operating nominally."}])
        brief = self.generate_briefing(title, sections)

        self.log_action("generate_report", title, "SUCCESS", {"sections": len(sections)})
        return {
            "status": "reported",
            "report": brief,
        }
